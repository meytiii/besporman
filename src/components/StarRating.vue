<script setup lang="ts">
import { computed } from 'vue'

const props = withDefaults(
  defineProps<{
    rating: number;
    showScore?: boolean;
    uid?: string;
  }>(),
  {
    showScore: true,
    uid: () => Math.random().toString(36).substring(2, 9),
  }
)

const clipUid = computed(() => props.uid)

type StarType = 'full' | 'half' | 'empty'

const getStarType = (index: number): StarType => {
  if (props.rating >= index) {
    return 'full'
  }
  if (props.rating >= index - 0.5) {
    return 'half'
  }
  return 'empty'
}

const formattedScore = computed(() => {
  const rounded = Math.round(props.rating * 2) / 2
  const formatted = rounded % 1 === 0 ? rounded.toFixed(1) : rounded.toString()
  const farsiDigits = ['۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹']
  return formatted.replace(/\d/g, (d) => farsiDigits[parseInt(d, 10)]).replace('.', '٫')
})
</script>

